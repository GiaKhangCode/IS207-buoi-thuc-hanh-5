    MASP CHAR(4) NOT NULL,
    TENSP VARCHAR(50) NOT NULL,
    DVT VARCHAR(50) NOT NULL,
    NUOCSX VARCHAR(20) NOT NULL,
    GIA INT(11) NOT NULL,
    HINHANH VARCHAR(40) NOT NULL,
    LOAISP VARCHAR(20) NOT NULL,
