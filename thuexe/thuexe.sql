CREATE DATABASE IF NOT EXISTS thuexe CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE thuexe;

CREATE TABLE KHACHHANG (
    MAKH VARCHAR(10) PRIMARY KEY,
    TENKH VARCHAR(100) NOT NULL,
    SDT VARCHAR(20) NOT NULL,
    DIACHI VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE XE (
    SOXE VARCHAR(20) PRIMARY KEY,
    TENXE VARCHAR(100) NOT NULL,
    HANGXE VARCHAR(50) NOT NULL,
    SOCHO VARCHAR(3) NOT NULL,
    NAMSX CHAR(4) NOT NULL,
    DGTHUE DECIMAL(12, 2) NOT NULL CHECK (DGTHUE > 0),
    TINHTRANG BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;

CREATE TABLE THUE (
    MAT VARCHAR(20) PRIMARY KEY,
    MAKH VARCHAR(10) NOT NULL,
    SOXE VARCHAR(20) NOT NULL,
    NGAYTHUE DATE NOT NULL,
    NGAYTRA DATE DEFAULT NULL,
    GIATHUE DECIMAL(15, 2) DEFAULT NULL,
    FOREIGN KEY (MAKH) REFERENCES KHACHHANG (MAKH),
    FOREIGN KEY (SOXE) REFERENCES XE (SOXE),
    CHECK (NGAYTRA IS NULL OR NGAYTRA >= NGAYTHUE),
    INDEX (MAKH, NGAYTRA),
    INDEX (SOXE, NGAYTRA),
    INDEX (NGAYTHUE, NGAYTRA)
) ENGINE=InnoDB;

